#!/bin/sh
# Writes docs/site/demo/data.js, the live demo's data, from the synthetic
# demo home (app/scripts/demo-home.sh) through hippo's --json twins:
# hippo view morning|strip|map|note|counts and hippo brief. Nothing in it is
# written by hand, and nothing comes from a real home.
#
#   HIPPO_BIN=<path to hippo> docs/site/demo-data.sh     # macOS (BSD date)
#
# Every run uses a new temporary home and user directory inside the build
# folder, never ~/.hippo or ~/.claude*, and deletes them at the end. Times
# in the data are the demo home's, which it stamps relative to now.
set -eu
# Clock times in the data are in UTC, so no machine's time zone is in it.
TZ=UTC
export TZ

root=$(cd "$(dirname "$0")/../.." && pwd)
bin=${HIPPO_BIN:-$root/target/debug/hippo}
[ -x "$bin" ] || {
  echo "demo-data: no hippo binary at $bin (set HIPPO_BIN)" >&2
  exit 2
}
bin=$(cd "$(dirname "$bin")" && pwd)/$(basename "$bin")
# Not under /var/folders: the lessons pass counts sessions there as a
# program's and drafts nothing from them.
mkdir -p "$root/target"
tmp=$(mktemp -d "$root/target/demo-data.XXXXXX")
trap 'rm -rf "$tmp"' EXIT INT TERM
mkdir -p "$tmp/user"

HOME=$tmp/user CODEX_HOME=$tmp/user/.codex CLAUDE_CONFIG_DIR=$tmp/user/.claude \
  HIPPO_DEMO_WS=tern HIPPO_BIN=$bin PATH=/usr/bin:/bin \
  sh "$root/app/scripts/demo-home.sh" "$tmp/demo" >/dev/null

run() {
  HOME=$tmp/user CODEX_HOME=$tmp/user/.codex CLAUDE_CONFIG_DIR=$tmp/user/.claude \
    HIPPO_HOME=$tmp/demo/home HIPPO_T3_STATE=$tmp/demo/t3/statev2.sqlite PATH=/usr/bin:/bin \
    "$bin" "$@"
}

morning=$(run view morning --json)
strip=$(run view strip --json)
map=$(run view map --json)
# The demo home answers with a stub model (fixtures/stub-model), so its
# Ask bar names the stub; the page shows what a default install's says.
counts=$(run view counts --json | /usr/bin/python3 -I -c '
import json, sys
c = json.load(sys.stdin)
c["ask"] = {"runner": "claude", "agent": {"code": "cc", "name": "Claude Code"},
            "account": None, "label": "Claude Code answers", "known": True}
print(json.dumps(c, separators=(",", ":")))')
brief=$(run brief --task "Run a preview of the album page" --json)
# The note the replica opens on: the first with a rule waiting.
note=$(printf '%s' "$map" | /usr/bin/python3 -I -c '
import json, sys
m = json.load(sys.stdin)
pick = next((n for n in m["notes"] if n["flags"]["waiting"]), None) or next(n for n in m["notes"] if n["flags"]["entry"])
print(pick["path"])')
notes=$(printf '%s' "$map" | /usr/bin/python3 -I -c '
import json, sys
for n in json.load(sys.stdin)["notes"]:
    print(n["path"])')

out=$root/docs/site/demo/data.js
{
  printf '/* Generated by docs/site/demo-data.sh from the synthetic demo home\n'
  printf '   (app/scripts/demo-home.sh) through hippo view --json and hippo brief\n'
  printf '   --json. Do not edit by hand. */\n'
  printf 'window.HIPPO_DEMO = {\n'
  printf '"selected": %s,\n' "$(printf '%s' "$note" | /usr/bin/python3 -I -c 'import json,sys; print(json.dumps(sys.stdin.read().strip()))')"
  printf '"morning": %s,\n' "$morning"
  printf '"strip": %s,\n' "$strip"
  printf '"map": %s,\n' "$map"
  printf '"counts": %s,\n' "$counts"
  printf '"brief": %s,\n' "$brief"
  printf '"notes": {\n'
  first=1
  printf '%s\n' "$notes" | while IFS= read -r p; do
    [ -n "$p" ] || continue
    j=$(run view note "$p" --json)
    if [ $first -eq 0 ]; then printf ',\n'; fi
    first=0
    printf '%s: %s' "$(printf '%s' "$p" | /usr/bin/python3 -I -c 'import json,sys; print(json.dumps(sys.stdin.read().strip()))')" "$j"
  done
  printf '\n}\n};\n'
} | sed -e "s#$tmp/demo/tern#~/code/tern#g" -e "s#$tmp/demo#~/demo#g" -e "s#$tmp/user#~#g" >"$out.tmp"

# No path of this machine may be left in it.
if grep -q "$tmp\|/Users/\|/private/" "$out.tmp"; then
  echo "demo-data: a local path is left in the data" >&2
  rm -f "$out.tmp"
  exit 1
fi
mv "$out.tmp" "$out"
echo "wrote $out ($(wc -c <"$out" | tr -d ' ') bytes)"
